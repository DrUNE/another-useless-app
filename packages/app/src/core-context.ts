import type { Core } from "@app/core-api";
import { createContext } from "solid-js";

/**
 * Ядро, которое точка входа подставляет интерфейсу. Без провайдера `useContext` бросает ошибку (контекст без значения
 * по умолчанию): интерфейс не должен молча работать с «никаким» ядром.
 *
 * Отличие от React: сам контекст и есть провайдер (`<CoreContext value={core}>`), а подписка на значение не перерисовывает
 * компоненты, потому что тело компонента выполняется один раз.
 */
export const CoreContext = createContext<Core>();
